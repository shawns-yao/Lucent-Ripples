import test from 'node:test';
import assert from 'node:assert/strict';
import {celestialAt, projectReflection, REFERENCE_LOCATION} from '../src/celestial.js';

const RAD = Math.PI / 180;
const near = (actual, expected, tolerance = 1e-8) => assert.ok(Math.abs(actual - expected) < tolerance, `${actual} is not within ${tolerance} of ${expected}`);
const at = (date, location = {lat:0, lon:0}, rest = {}) => celestialAt({date:new Date(date), location, ...rest});

test('positions and lunar phase agree with pinned upstream SunCalc 1.9 reference fixtures', () => {
  // External reference values, not generated by this implementation:
  // https://github.com/mourner/suncalc/blob/v1.9.0/test.js
  // SunCalc 1.9 uses south-origin azimuth; our API adds PI to make north zero.
  const result = at('2013-03-05T00:00:00Z', {lat:50.5, lon:30.5});
  near(result.sun.altitude, -.7000406838781611);
  near(result.sun.azimuth, -2.5003175907168385 + Math.PI);
  near(result.moon.altitude, .014551482243892251);
  near(result.moon.azimuth, -.9783999522438226 + Math.PI);
  near(result.moon.distance, 364121.37256256194, 1e-6);
  near(result.moon.illumination, .4848068202456373);
  near(result.moon.phase, .7548368838538762);
  near(result.moon.brightLimbAngle, 1.6732942678578346);
});

test('equinox geometry: equatorial transit is overhead; mid-latitude transit is due south', () => {
  // Independent spherical geometry: at the March equinox declination is ~0;
  // altitude at transit is 90° minus latitude. Equation of time delays Greenwich
  // apparent noon ~7.5 minutes; allow 1° for the low-order model/calendar date.
  const equator = at('2026-03-20T12:08:00Z');
  const northern = at('2026-03-20T12:08:00Z', {lat:40, lon:0});
  assert.ok(equator.sun.altitude > 89 * RAD);
  near(northern.sun.altitude, 50 * RAD, 1 * RAD);
  near(northern.sun.azimuth, Math.PI, 1 * RAD);
  const morning = at('2026-03-20T08:00:00Z', {lat:40, lon:0});
  const afternoon = at('2026-03-20T16:00:00Z', {lat:40, lon:0});
  assert.ok(morning.sun.azimuth < Math.PI && afternoon.sun.azimuth > Math.PI);
  assert.ok(morning.sun.reflection.x > .5 && afternoon.sun.reflection.x < .5);
});

test('same instant uses both selected longitude and latitude, including opposite hemispheres', () => {
  const date = '2026-03-20T12:08:00Z';
  const greenwich = at(date), antipode = at(date, {lat:0, lon:180});
  assert.ok(greenwich.sun.altitude > 89 * RAD);
  assert.ok(antipode.sun.altitude < -89 * RAD);
  assert.equal(antipode.sun.visibility, 0);
  assert.notDeepEqual(greenwich.moon.direction, antipode.moon.direction);
  const south = at(date, {lat:-40, lon:0});
  near(south.sun.altitude, 50 * RAD, 1 * RAD);
  assert.ok(south.sun.azimuth < 1 * RAD || south.sun.azimuth > 359 * RAD);
});

test('automatic moon is hidden below the horizon; sky motion comes from Date alone', () => {
  const snapshots = Array.from({length:24}, (_, hour) => at(`2026-10-02T${String(hour).padStart(2,'0')}:00:00Z`, {lat:39.9, lon:116.4}));
  const below = snapshots.filter(s => s.moon.altitude <= 0);
  const above = snapshots.filter(s => s.moon.altitude > 0);
  assert.ok(below.length > 0 && above.length > 0);
  for (const s of below) { assert.equal(s.moon.visibility, 0); assert.equal(s.moon.aboveHorizon, false); }
  assert.notDeepEqual(snapshots[12].moon.reflection, snapshots[13].moon.reflection);
  const first = snapshots[0];
  assert.deepEqual(first, at('2026-10-02T00:00:00Z', {lat:39.9, lon:116.4}));
});

test('new Moon matches the independently documented 2024-04-08 solar eclipse', () => {
  // NASA lists Dallas maximum at 1:42 p.m. CDT = 18:42 UTC on 2024-04-08.
  // https://science.nasa.gov/eclipses/future-eclipses/eclipse-2024/where-when/
  const eclipse = at('2024-04-08T18:42:00Z', {lat:32.78, lon:-96.8});
  assert.ok(eclipse.moon.illumination < .01);
  assert.ok(eclipse.moon.phase < .025 || eclipse.moon.phase > .975);
  near(eclipse.moon.altitude, eclipse.sun.altitude, 3 * RAD);
});

test('explicit previews override actual horizon and phase and are clearly labeled', () => {
  const midnight = '2026-03-20T00:00:00Z';
  const day = at(midnight, {lat:89, lon:0}, {timeMode:'day'});
  const night = at(midnight, {lat:89, lon:0}, {timeMode:'night'});
  assert.equal(day.isPreview, true);
  assert.match(day.label, /白昼预览/);
  assert.equal(day.sun.visibility, 1);
  assert.equal(day.moon.visibility, 0);
  assert.match(night.label, /夜景预览.*非当前月相/);
  assert.equal(night.moon.visibility, 1);
  assert.equal(night.moon.phase, .5);
  assert.equal(night.sun.visibility, 0);
  const later = at('2026-03-22T12:00:00Z', {lat:-89, lon:120}, {timeMode:'night'});
  assert.deepEqual(night.moon, later.moon);
});

test('weather attenuates direct light without moving sky or changing phase', () => {
  const settings = {date:new Date('2026-10-02T00:00:00Z'), timeMode:'day'};
  const clear = celestialAt({...settings, weather:{cloud:0, rain:0}});
  const cloudy = celestialAt({...settings, weather:{cloud:.95, rain:0}});
  const rainy = celestialAt({...settings, weather:{cloud:.95, rain:.8}});
  assert.ok(clear.sun.visibility > cloudy.sun.visibility * 5);
  assert.ok(cloudy.sun.visibility > rainy.sun.visibility);
  assert.deepEqual(clear.sun.direction, rainy.sun.direction);
  assert.deepEqual(clear.sun.reflection, rainy.sun.reflection);
  const obscuredPreview = celestialAt({...settings, timeMode:'night', weather:{cloud:1, rain:1, snow:1}});
  assert.ok(obscuredPreview.moon.visibility > 0);
});

test('missing location is explicitly Beijing reference, never silently equator or device timezone', () => {
  const missing = celestialAt({date:new Date('2026-10-02T04:00:00Z')});
  assert.equal(missing.isReferenceLocation, true);
  assert.equal(missing.location.lat, REFERENCE_LOCATION.lat);
  assert.equal(missing.location.lon, REFERENCE_LOCATION.lon);
  assert.match(missing.label, /北京参考坐标.*未选择位置/);
  const selected = at('2026-10-02T04:00:00Z', {lat:39.9, lon:116.4});
  assert.equal(selected.isReferenceLocation, false);
  assert.deepEqual(selected.sun, missing.sun);
  for (const location of [{lat:91,lon:0}, {lat:0,lon:181}, {lat:null,lon:0}, {lat:NaN,lon:0}]) {
    assert.equal(celestialAt({location}).isReferenceLocation, true);
  }
});

test('fixed projection is north-up, bounded, and independent of frame or world size', () => {
  near(projectReflection(0, 0).x, .5);
  near(projectReflection(0, 0).y, .20);
  near(projectReflection(0, Math.PI / 2).x, .80);
  near(projectReflection(0, Math.PI).y, .70);
  near(projectReflection(0, 3 * Math.PI / 2).x, .20);
  near(projectReflection(Math.PI / 2, 0).y, .45);
  for (const lat of [-90,-89,0,89,90]) for (const lon of [-180,0,180]) {
    const result = at('2026-06-21T00:00:00Z', {lat,lon});
    for (const body of [result.sun,result.moon]) {
      assert.ok(Number.isFinite(body.altitude + body.azimuth));
      assert.ok(body.visibility >= 0 && body.visibility <= 1);
      assert.ok(body.reflection.x >= 0 && body.reflection.x <= 1 && body.reflection.y >= 0 && body.reflection.y <= 1);
      near(body.direction.x ** 2 + body.direction.y ** 2 + body.direction.z ** 2, 1);
    }
  }
});

test('invalid date and unknown time mode fail explicitly', () => {
  assert.throws(() => celestialAt({date:new Date('invalid')}), /valid Date/);
  assert.throws(() => celestialAt({date:'2026-10-02'}), /valid Date/);
  assert.throws(() => celestialAt({timeMode:'accelerated'}), /time mode/);
});
